// Generates client/public/_redirects (Cloudflare Pages / Netlify format) from the
// old Express redirects in server/redirects.ts. Re-run if cities/counties change.
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const loc = fs.readFileSync(path.join(root, "client/src/data/locations.ts"), "utf8");
const counties = ["westchester", "dutchess", "orange", "putnam", "rockland", "ulster"];
// City slugs = every `slug: "..."` in locations.ts that isn't a county
const cities = [...loc.matchAll(/slug:\s*"([^"]+)"/g)].map(m => m[1]).filter(s => !counties.includes(s));

const lines = [
  "# Generated by scripts/gen-redirects.mjs. Ported from the old Manus server/redirects.ts",
  "/contact-us        /contact   301",
  "/contact-us/       /contact   301",
  "/about-us          /about     301",
  "/about-us/         /about     301",
  "/faqs              /faq       301",
  "/faqs/             /faq       301",
  "# (/faq/ -> /faq is automatic on Cloudflare Pages; the old explicit rule caused a redirect loop on Manus)",
  "/feed              /blog      301",
  "/feed/             /blog      301",
  "/what-are-the-benefits-of-selling-a-house-for-cash-in-city   /we-buy-houses-hudson-valley-ny 301",
  "/what-are-the-benefits-of-selling-a-house-for-cash-in-city/  /we-buy-houses-hudson-valley-ny 301",
  "",
  "# Old /city/<county>[-county][-N] URLs -> county hub (old code stripped a trailing -digits)",
];
for (const c of counties) {
  const target = `/sell-my-house-fast-${c}-county-ny`;
  for (const base of [c, `${c}-county`]) {
    for (const suf of ["", ...Array.from({ length: 12 }, (_, i) => `-${i + 1}`)]) {
      lines.push(`/city/${base}${suf}  ${target} 301`, `/city/${base}${suf}/  ${target} 301`);
    }
  }
}
lines.push("", "# Old /city/<city> URLs -> city page");
for (const c of [...new Set(cities)]) {
  const target = `/sell-my-house-fast-${c}-ny`;
  for (const suf of ["", "-1", "-2", "-3"]) {
    lines.push(`/city/${c}${suf}  ${target} 301`, `/city/${c}${suf}/  ${target} 301`);
  }
}
lines.push("", "# Fallback (same as old code): /city/<slug> -> /sell-my-house-fast-<slug>-ny", "/city/:slug   /sell-my-house-fast-:slug-ny 301", "/city/:slug/  /sell-my-house-fast-:slug-ny 301", "");
fs.writeFileSync(path.join(root, "client/public/_redirects"), lines.join("\n"));
const n = lines.filter(l => l && !l.startsWith("#")).length;
console.log(`_redirects: ${n} rules (${cities.length} cities)`);
if (n > 2000) throw new Error("Cloudflare Pages allows max 2000 static redirects");
